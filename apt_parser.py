"""
ISO 4343 APT Toolpath Parser and Verifier Orchestrator.

Parses intermediate APT (.apt) files generated by Autodesk CAM (apt.cps) into
normalized metric MotionSegment sequences, and feeds them into IVerificationEngine.

Zero G-code dialect dependence; standardized metric units (mm, mm/min, sec).
"""

import math
import os
import re
from typing import Dict, List, Optional, Sequence, Tuple

from geometry.models import (
    MotionKind,
    MotionSegment,
    Vector3D,
    VectorKey,
    ToolAssembly,
    WorkpieceDefinition,
    VerificationReport,
)
from geometry.engine_interface import IVerificationEngine


class APTParser:
    """
    Parser for ISO 4343 Common APT files generated by Autodesk CAM (apt.cps).
    Translates raw APT statements (GOTO, MOVARC, RAPID, FEDRAT, LOADTL, SPINDL)
    into normalized metric MotionSegment sequences.
    """

    def __init__(self, default_rapid_feed_mmpm: float = 5000.0):
        self.default_rapid_feed_mmpm = default_rapid_feed_mmpm

    def parse_file(self, filepath: str, batch_idx: int = 0, start_segment_id: int = 0) -> List[MotionSegment]:
        """Parse an APT file on disk into a list of MotionSegments."""
        with open(filepath, "r", encoding="utf-8", errors="replace") as f:
            content = f.read()
        return self.parse_text(content, batch_idx=batch_idx, start_segment_id=start_segment_id)

    def parse_text(self, content: str, batch_idx: int = 0, start_segment_id: int = 0) -> List[MotionSegment]:
        """Parse raw APT text into a list of MotionSegments."""
        segments: List[MotionSegment] = []

        # Modal Parser State
        scale = 1.0               # 1.0 for MM, 25.4 for INCHES
        pending_comment: Optional[str] = None
        current_op = "INIT"
        sec_id = -1
        current_tool_id = 0
        current_spindle_rpm = 1000.0
        current_feedrate_mmpm = 250.0
        is_rapid = False
        in_cycle = False
        segment_id = start_segment_id
        current_pos: Optional[Vector3D] = None
        pending_arc: Optional[Dict[str, Any]] = None

        lines = content.splitlines()
        for raw_line in lines:
            line = raw_line.strip()
            if not line:
                continue

            # 1. Unit setting
            if line.startswith("UNITS/"):
                unit_str = line.split("/")[1].strip().upper()
                scale = 1.0 if "MM" in unit_str else 25.4
                continue

            # 2. PPRINT comments
            if line.startswith("PPRINT/"):
                m = re.match(r"PPRINT/'([^']*)'", line)
                if m:
                    comment = m.group(1).strip()
                    # Filter out Personal Use license warnings, UNNAMED, and empty lines
                    boilerplate = ("Personal Use", "feedrate of rapid", "machining time", "Subscription", "UNNAMED")
                    if comment and not any(w in comment for w in boilerplate):
                        pending_comment = comment
                continue

            # 3. Section boundary: CUTTER marks the beginning of each toolpath section
            if line.startswith("CUTTER/"):
                sec_id += 1
                if pending_comment:
                    current_op = pending_comment
                    pending_comment = None
                continue

            # 4. Tool call
            if line.startswith("LOADTL/"):
                payload = line.split("/")[1].strip()
                tokens = [t.strip() for t in payload.split(",")]
                try:
                    current_tool_id = int(tokens[0])
                except (ValueError, IndexError):
                    pass
                continue

            # 4. Spindle control
            if line.startswith("SPINDL/"):
                payload = line.split("/")[1].strip()
                tokens = [t.strip() for t in payload.split(",")]
                try:
                    current_spindle_rpm = float(tokens[0])
                except (ValueError, IndexError):
                    pass
                continue

            # 5. Motion Modes
            if line == "RAPID":
                is_rapid = True
                continue

            # 6. Feedrate
            if line.startswith("FEDRAT/"):
                payload = line.split("/")[1].strip()
                tokens = [t.strip() for t in payload.split(",")]
                try:
                    val = float(tokens[0])
                    unit_token = tokens[1].upper() if len(tokens) > 1 else "MMPM"
                    if "IPR" in unit_token:
                        feed_val_mm = val * 25.4
                        is_per_rev = True
                    elif "MMPR" in unit_token:
                        feed_val_mm = val
                        is_per_rev = True
                    elif "IPM" in unit_token:
                        feed_val_mm = val * 25.4
                        is_per_rev = False
                    else:
                        feed_val_mm = val if "MM" in unit_token else (val * 25.4)
                        is_per_rev = False

                    if is_per_rev:
                        effective_rpm = current_spindle_rpm if current_spindle_rpm > 0 else 1000.0
                        current_feedrate_mmpm = feed_val_mm * effective_rpm
                    else:
                        current_feedrate_mmpm = feed_val_mm

                    is_rapid = False
                except (ValueError, IndexError):
                    pass
                continue

            # 7. Canned Cycles
            if line.startswith("CYCLE/OFF"):
                in_cycle = False
                continue
            elif line.startswith("CYCLE/"):
                in_cycle = True
                continue

            # 8. Circular Arc Definition (MOVARC)
            if line.startswith("MOVARC/"):
                payload = line.split("/")[1].strip()
                tokens = [t.strip() for t in payload.split(",")]
                try:
                    cx = float(tokens[0]) * scale
                    cy = float(tokens[1]) * scale
                    cz = float(tokens[2]) * scale
                    nx = float(tokens[3])
                    ny = float(tokens[4])
                    nz = float(tokens[5])
                    radius = float(tokens[6]) * scale
                    # tokens[7] is 'ANGLE', tokens[8] is sweep in degrees
                    sweep_deg = float(tokens[8])
                    pending_arc = {
                        "center": Vector3D(cx, cy, cz),
                        "normal": Vector3D(nx, ny, nz),
                        "radius": radius,
                        "sweep_deg": sweep_deg,
                    }
                except (ValueError, IndexError):
                    pending_arc = None
                continue

            # 9. Linear / Arc Endpoint Move (GOTO)
            if line.startswith("GOTO/"):
                payload = line.split("/")[1].strip()
                tokens = [t.strip() for t in payload.split(",")]
                try:
                    ex = float(tokens[0]) * scale
                    ey = float(tokens[1]) * scale
                    ez = float(tokens[2]) * scale
                    end_pos = Vector3D(ex, ey, ez)
                except (ValueError, IndexError):
                    continue

                if current_pos is not None:
                    # Construct MotionSegment
                    segment_id += 1
                    dist = math.hypot(end_pos.x - current_pos.x, end_pos.y - current_pos.y, end_pos.z - current_pos.z)

                    if pending_arc is not None:
                        is_arc = True
                        arc_center = pending_arc["center"]
                        # Determine clockwise vs counter-clockwise from normal
                        # In ZX plane (turning), normal along -Y is CW, +Y is CCW
                        motion = MotionKind.ARC_CW if pending_arc["normal"].y < 0 else MotionKind.ARC_CCW
                        arc_len = pending_arc["radius"] * math.radians(abs(pending_arc["sweep_deg"]))
                        dist = max(dist, arc_len)
                    else:
                        is_arc = False
                        arc_center = None
                        motion = MotionKind.RAPID if is_rapid else MotionKind.LINEAR

                    feed = self.default_rapid_feed_mmpm if motion == MotionKind.RAPID else current_feedrate_mmpm
                    duration = (dist / max(1.0, feed)) * 60.0 if feed > 0 else 0.0

                    v_key = VectorKey.from_floats(sec_id, current_pos, end_pos)

                    seg = MotionSegment(
                        segment_id=segment_id,
                        op_id=current_op,
                        sec_id=sec_id,
                        motion=motion,
                        start=current_pos,
                        end=end_pos,
                        feedrate_mmpm=feed,
                        spindle_rpm=current_spindle_rpm,
                        duration_sec=duration,
                        vector_key=v_key,
                        is_arc=is_arc,
                        arc_center=arc_center,
                        arc_plane="ZX" if abs(end_pos.y) < 1e-4 else "XY",
                        metadata={
                            "tool_id": current_tool_id,
                            "in_cycle": in_cycle,
                            "raw_apt": line,
                            "batch_idx": batch_idx,
                            "batch_sec_id": sec_id,
                        },
                    )
                    segments.append(seg)

                current_pos = end_pos
                is_rapid = False
                pending_arc = None
                continue

            # 10. Dwell / Delay
            if line.startswith("DELAY/") or line.startswith("DWELL/"):
                payload = line.split("/")[1].strip()
                try:
                    dwell_sec = float(payload)
                except ValueError:
                    dwell_sec = 1.0

                if current_pos is not None:
                    segment_id += 1
                    seg = MotionSegment(
                        segment_id=segment_id,
                        op_id=current_op,
                        sec_id=sec_id,
                        motion=MotionKind.DWELL,
                        start=current_pos,
                        end=current_pos,
                        feedrate_mmpm=0.0,
                        spindle_rpm=current_spindle_rpm,
                        duration_sec=dwell_sec,
                        vector_key=VectorKey.from_floats(sec_id, current_pos, current_pos),
                        is_arc=False,
                        arc_center=None,
                        metadata={
                            "tool_id": current_tool_id,
                            "batch_idx": batch_idx,
                            "batch_sec_id": sec_id,
                        },
                    )
                    segments.append(seg)
                continue

        return segments

    def parse_apt_batches(self, filepaths: Sequence[str]) -> List[MotionSegment]:
        """Parse multiple per-batch APT files into a continuous, ordered MotionSegment sequence."""
        all_segments: List[MotionSegment] = []
        cur_seg_id = 0
        for b_idx, fp in enumerate(filepaths):
            batch_segs = self.parse_file(fp, batch_idx=b_idx, start_segment_id=cur_seg_id)
            all_segments.extend(batch_segs)
            cur_seg_id = len(all_segments)
        return all_segments


def parse_apt_file(filepath: str) -> List[MotionSegment]:
    """Convenience helper to parse an APT file into MotionSegments."""
    return APTParser().parse_file(filepath)


def parse_apt_batches(filepaths: Sequence[str]) -> List[MotionSegment]:
    """Parse multiple per-batch APT files into a single unified MotionSegment sequence."""
    return APTParser().parse_apt_batches(filepaths)


def verify_apt_toolpath(
    apt_filepath: str,
    verifier: IVerificationEngine,
    workpiece: WorkpieceDefinition,
    tools_by_op: Dict[str, ToolAssembly],
) -> VerificationReport:
    """
    High-level orchestrator:
    1. Parses an APT toolpath into canonical metric MotionSegments.
    2. Runs complete IVerificationEngine simulation.
    3. Returns VerificationReport containing promoted_vectors for universal_wrapper.cps.
    """
    segments = parse_apt_file(apt_filepath)
    return verifier.verify_toolpath(segments, tools_by_op, workpiece)
